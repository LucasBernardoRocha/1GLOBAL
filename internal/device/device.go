package device

import (
	"errors"
	"fmt"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/google/uuid"
)

// State represents the lifecycle state of a device.
type State string

const (
	StateAvailable State = "available"
	StateInUse     State = "in-use"
	StateInactive  State = "inactive"
)

const (
	maxNameLength  = 120
	maxBrandLength = 80
)

// Valid reports whether the state is part of the supported domain.
func (s State) Valid() bool {
	switch s {
	case StateAvailable, StateInUse, StateInactive:
		return true
	default:
		return false
	}
}

// Domain errors are deliberately small and transport agnostic. The HTTP layer
// maps them to status codes without leaking storage details.
var (
	ErrNotFound           = errors.New("device not found")
	ErrInUse              = errors.New("device is in use")
	ErrImmutableCreatedAt = errors.New("created_at cannot be updated")
)

// ValidationError describes an invalid input field.
type ValidationError struct {
	Field   string
	Message string
}

func (e *ValidationError) Error() string {
	if e.Field == "" {
		return e.Message
	}
	return fmt.Sprintf("%s: %s", e.Field, e.Message)
}

// Device is the persisted representation of a device resource.
type Device struct {
	ID        uuid.UUID `json:"id"`
	Name      string    `json:"name"`
	Brand     string    `json:"brand"`
	State     State     `json:"state"`
	CreatedAt time.Time `json:"created_at"`
}

// CreateInput contains the mutable fields accepted when creating a device.
// created_at is intentionally absent: it is always generated by the server.
type CreateInput struct {
	Name  string `json:"name"`
	Brand string `json:"brand"`
	State State  `json:"state,omitempty"`
}

// UpdateInput uses pointers to distinguish omitted fields from zero values.
// created_at is present only so the API can reject an explicit attempt to
// change it with a clear validation error instead of silently ignoring it.
type UpdateInput struct {
	Name      *string    `json:"name,omitempty"`
	Brand     *string    `json:"brand,omitempty"`
	State     *State     `json:"state,omitempty"`
	CreatedAt *time.Time `json:"created_at,omitempty"`
}

// Normalize trims user-provided strings and applies the default state.
func (in *CreateInput) Normalize() {
	in.Name = strings.TrimSpace(in.Name)
	in.Brand = strings.TrimSpace(in.Brand)
	if in.State == "" {
		in.State = StateAvailable
	}
}

// Validate checks the normalized create input.
func (in *CreateInput) Validate() error {
	if err := validateName(in.Name); err != nil {
		return err
	}
	if err := validateBrand(in.Brand); err != nil {
		return err
	}
	if !in.State.Valid() {
		return &ValidationError{Field: "state", Message: "must be one of: available, in-use, inactive"}
	}
	return nil
}

// Normalize trims user-provided strings on update.
func (in *UpdateInput) Normalize() {
	if in.Name != nil {
		name := strings.TrimSpace(*in.Name)
		in.Name = &name
	}
	if in.Brand != nil {
		brand := strings.TrimSpace(*in.Brand)
		in.Brand = &brand
	}
}

// Validate checks the normalized update input.
func (in *UpdateInput) Validate() error {
	if in.CreatedAt != nil {
		return ErrImmutableCreatedAt
	}
	if in.Name != nil {
		if err := validateName(*in.Name); err != nil {
			return err
		}
	}
	if in.Brand != nil {
		if err := validateBrand(*in.Brand); err != nil {
			return err
		}
	}
	if in.State != nil && !in.State.Valid() {
		return &ValidationError{Field: "state", Message: "must be one of: available, in-use, inactive"}
	}
	return nil
}

func validateName(name string) error {
	if name == "" {
		return &ValidationError{Field: "name", Message: "is required"}
	}
	if utf8.RuneCountInString(name) > maxNameLength {
		return &ValidationError{Field: "name", Message: fmt.Sprintf("must be at most %d characters", maxNameLength)}
	}
	return nil
}

func validateBrand(brand string) error {
	if brand == "" {
		return &ValidationError{Field: "brand", Message: "is required"}
	}
	if utf8.RuneCountInString(brand) > maxBrandLength {
		return &ValidationError{Field: "brand", Message: fmt.Sprintf("must be at most %d characters", maxBrandLength)}
	}
	return nil
}

// Filter narrows a device listing. Empty fields are ignored.
type Filter struct {
	Brand string
	State State
}

// StateChangedEvent is emitted after a state transition has been committed.
type StateChangedEvent struct {
	DeviceID      uuid.UUID `json:"device_id"`
	PreviousState State     `json:"previous_state"`
	NewState      State     `json:"new_state"`
	ChangedAt     time.Time `json:"changed_at"`
}

// Notifier publishes committed state changes.
type Notifier interface {
	Publish(event StateChangedEvent)
}

// Subscriber exposes a stream of state changes to SSE clients.
type Subscriber interface {
	Subscribe() (<-chan StateChangedEvent, func())
}
